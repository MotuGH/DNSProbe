const {rankResults, latencyMetric, resultStatus}=require('./web/ranking.js');
const assert=require('node:assert/strict');
const row=(server,status,ms,error='')=>({server,status,ms,error,transport:'doh3',domain:'example.com',type:'A'});
assert.deepEqual(rankResults([row('fast-error','error',1,'timeout'),row('slow','passed',500),row('fast','passed',100),row('fake','suspicious',1)]).map(x=>x.key),['fast-error / DOH3','fake / DOH3','fast / DOH3','slow / DOH3']);
const ranked=rankResults([row('a','passed',100),row('a','error',5000,'timeout'),row('b','passed',200),row('b','passed',200),row('b','error',5000,'timeout')]);assert.equal(ranked[0].key,'a / DOH3');assert.equal(ranked[0].latency.value,100);assert.deepEqual(rankResults([]),[]);
const fake = {...row('vpn','suspicious',1), notes:['Служебный/непубличный адрес: 198.18.1.188']};
assert.equal(resultStatus(fake),'local');
assert.equal(rankResults([fake])[0].badRate,0);
assert.equal(rankResults([{...fake, status:'error'}])[0].errors,1);
assert.equal(resultStatus({...fake, notes:[...fake.notes,'NXDOMAIN расходится с положительным ответом']}),'suspicious');
const samples=Array.from({length:20},(_,i)=>row('test','passed',i+1));
assert.equal(latencyMetric(samples.slice(0,19)).value,10);
assert.equal(latencyMetric([...samples.slice(0,19),fake]).label,'p50');
assert.equal(latencyMetric(samples).label,'p95');
assert.equal(latencyMetric(samples).value,19);
console.log('Ranking checks passed');
